#!/usr/bin/env node
// MoErgo layout-editor JSON (my.moergo.com) -> ZMK glove80.keymap + glove80.conf
// usage: node tools/layout2zmk.mjs [layout.json] [outdir]
import fs from 'node:fs';
import path from 'node:path';

const [, , src = 'my-layout.json', out = 'config'] = process.argv;
const cfg = JSON.parse(fs.readFileSync(src, 'utf8')).config;

// editor param name -> ZMK Kconfig
const KCONFIG = { HID_POINTING: 'CONFIG_ZMK_POINTING' };

// editor label -> ZMK label
const LABEL = { reset: 'sys_reset' };

const binding = (b) => {
  if (!b) return '&trans';
  const label = '&' + (LABEL[b.value.replace(/^&/, '')] ?? b.value.replace(/^&/, ''));
  const params = (b.params ?? []).map((p) =>
    p.params?.length ? `${p.value}(${p.params.map((q) => q.value).join(',')})` : p.value
  );
  return [label, ...params].join(' ');
};

const nodeName = (s) => s.replace(/^&/, '').replace(/[^A-Za-z0-9_]/g, '_');

const macro = (m) => `        ${nodeName(m.name)}: ${nodeName(m.name)} {
            label = "${nodeName(m.name).toUpperCase()}";
            compatible = "zmk,behavior-macro";
            #binding-cells = <0>;
            wait-ms = <${m.waitMs ?? 2}>;
            tap-ms = <${m.tapMs ?? 5}>;
            bindings = <${m.bindings.map(binding).join('>, <')}>;
        };`;

// macros the stock Glove80 keymap defines and layouts reference by name
const STOCK_MACROS = `        rgb_ug_status_macro: rgb_ug_status_macro_0 {
            label = "RGB_UG_STATUS";
            compatible = "zmk,behavior-macro";
            #binding-cells = <0>;
            bindings = <&rgb_ug RGB_STATUS>;
        };
${[0, 1, 2, 3]
  .map(
    (n) => `        bt_${n}: bt_profile_macro_${n} {
            label = "BT_${n}";
            compatible = "zmk,behavior-macro";
            #binding-cells = <0>;
            bindings = <&out OUT_BLE>, <&bt BT_SEL ${n}>;
        };`
  )
  .join('\n')}`;

const layers = cfg.layers
  .map((keys, i) => {
    const name = `layer_${i}_${(cfg.layer_names?.[i] ?? `l${i}`).replace(/[^A-Za-z0-9_]/g, '_')}`;
    const rows = keys.map(binding).join(' ');
    return `        ${name} {
            bindings = <${rows}>;
        };`;
  })
  .join('\n\n');

const combos = (cfg.combos ?? [])
  .map(
    (c) => `        combo_${nodeName(c.name)} {
            timeout-ms = <${c.timeoutMs ?? 50}>;
            key-positions = <${c.keyPositions.join(' ')}>;${
              (c.layers ?? [0]).includes(-1)
                ? ''
                : `\n            layers = <${c.layers.join(' ')}>;`
            }
            bindings = <${binding(c.binding)}>;
        };`
  )
  .join('\n');

const keymap = `/*
 * GENERATED by tools/layout2zmk.mjs from ${path.basename(src)} — edit the JSON source, not this file.
 * Source layout: "${cfg.title ?? ''}" ${cfg.uuid ?? ''}
 */
#include <behaviors.dtsi>
#include <dt-bindings/zmk/keys.h>
#include <dt-bindings/zmk/bt.h>
#include <dt-bindings/zmk/ext_power.h>
#include <dt-bindings/zmk/outputs.h>
#include <dt-bindings/zmk/rgb.h>
#include <dt-bindings/zmk/pointing.h>

/ {
    behaviors {
        // editor emits &magic with no cells: hold = Magic layer, double-tap = RGB status
        magic: magic_tap_dance {
            label = "MAGIC";
            compatible = "zmk,behavior-tap-dance";
            #binding-cells = <0>;
            tapping-term-ms = <200>;
            bindings = <&mo ${(cfg.layer_names ?? []).indexOf('Magic')}>, <&rgb_ug_status_macro>;
        };
    };

    macros {
${[STOCK_MACROS, ...(cfg.macros ?? []).map(macro)].join('\n')}
    };

    keymap {
        compatible = "zmk,keymap";

${layers}
    };
};

${cfg.custom_devicetree ?? ''}
/ {
    combos {
        compatible = "zmk,combos";
${combos || '        /* none */'}
    };
};
`;

const conf = (cfg.config_parameters ?? [])
  .map(({ paramName, value }) =>
    KCONFIG[paramName] ? `${KCONFIG[paramName]}=${value}` : `# TODO unmapped editor param: ${paramName}=${value}`
  )
  .join('\n');

fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'glove80.keymap'), keymap);
fs.writeFileSync(path.join(out, 'glove80.conf'), conf + '\n');
console.log(
  `wrote ${out}/glove80.keymap  layers=${cfg.layers.length} keys=${cfg.layers[0].length} ` +
    `macros=${(cfg.macros ?? []).length} combos=${(cfg.combos ?? []).length} — conf: ${conf.replace(/\n/g, ' ')}`
);
